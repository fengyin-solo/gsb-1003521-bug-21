import type { EntryRow } from './types'

/**
 * 示例数据：首次打开时播种，之后浏览器里的改动优先，重置才会回到这份。
 * 各监测记录的站点编号都引用本站点表内真实存在的站点；撤销站（STAT-0004）下同时放了
 * 停用前（可补录）、停用后（禁止提交）两类记录；另保留一条找不到归属站点的水位记录。
 * STAT-0004 是缺少管理单位的老站点，由数据迁移按所在河流（淮河）回填。
 */

type RowInput = {
  id: number
  status: string
  fields: Record<string, string | number>
}

// 待处理/异常标志在数据迁移时按模块状态集合统一重算，这里先按同一口径播种。
function row(meta: { pending: string[]; abnormal: string[] }, input: RowInput): EntryRow {
  return {
    id: input.id,
    status: input.status,
    pending: meta.pending.includes(input.status),
    abnormal: meta.abnormal.includes(input.status),
    ...input.fields,
  }
}

